#!/usr/bin/env node
//
// The interpreter suite: interpreters given fixed programs (tools/wild/interp,
// see its README), specialized and measured by tools/wild.js. What counts is
// the speedup (the original's time per pass over the inputs over the
// residual's) and whether the program compiled away (no `// residue:` left).
//
//   node tools/interp.js [--filter REGEX] [--bin path] [--jobs N]
//                        [--json out.json] [--md docs/INTERP.md] [--keep DIR]
//
// Every other argument goes to tools/wild.js as it is. The environment does
// too: `PE_...=1 node tools/interp.js` measures the specializer so set.

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const root = path.resolve(__dirname, '..');
const casesDir = path.join(__dirname, 'wild', 'interp');
const argv = process.argv.slice(2);
let jsonOut = null;
let mdOut = null;
const pass = [];
for (let i = 0; i < argv.length; i++) {
  if (argv[i] === '--json') jsonOut = path.resolve(argv[++i]);
  else if (argv[i] === '--md') mdOut = path.resolve(argv[++i]);
  else pass.push(argv[i]);
}

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'interp-'));
const wildJson = path.join(tmp, 'wild.json');
const r = spawnSync(process.execPath, [path.join(__dirname, 'wild.js'), '--cases', casesDir, '--json', wildJson, ...pass], { stdio: ['ignore', 'inherit', 'inherit'] });
if (r.status !== 0 || !fs.existsSync(wildJson)) {
  console.error(`tools/wild.js failed (exit ${r.status})`);
  process.exit(1);
}
const wild = JSON.parse(fs.readFileSync(wildJson, 'utf8'));

const styleOf = (name) => {
  const src = fs.readFileSync(path.join(casesDir, name + '.mjs'), 'utf8');
  const m = src.match(/^\/\/ style: (.+)$/m);
  return m ? m[1].trim() : '';
};
const rows = wild.results.map((c) => ({
  name: c.name,
  style: styleOf(c.name),
  verdict: c.verdict,
  detail: c.detail,
  compiled: c.compiled,
  residueLeft: c.residueLeft,
  speedup: c.timing ? c.timing.originalUs / c.timing.residualUs : null,
  originalUs: c.timing ? c.timing.originalUs : null,
  residualUs: c.timing ? c.timing.residualUs : null,
  bundleLines: c.bundleLines,
  residualLines: c.residualLines,
  specMs: c.ms,
  rssMb: c.rssMb,
}));
rows.sort((a, b) => (b.speedup ?? -1) - (a.speedup ?? -1));

const timed = rows.filter((x) => x.speedup != null);
const geo = timed.length ? Math.exp(timed.reduce((s, x) => s + Math.log(x.speedup), 0) / timed.length) : NaN;
const claimed = rows.filter((x) => x.compiled != null);
const summary = {
  cases: rows.length,
  ok: rows.filter((x) => x.verdict === 'ok').length,
  wrong: rows.filter((x) => x.verdict === 'wrong').length,
  crash: rows.filter((x) => x.verdict === 'crash').length,
  other: rows.filter((x) => !['ok', 'wrong', 'crash'].includes(x.verdict)).length,
  geomeanSpeedup: geo,
  at2x: timed.filter((x) => x.speedup >= 2).length,
  slower: timed.filter((x) => x.speedup < 1).length,
  compiled: claimed.filter((x) => x.compiled).length,
  claimed: claimed.length,
};
const line =
  `INTERP ok ${summary.ok} wrong ${summary.wrong} crash ${summary.crash} other ${summary.other} (of ${summary.cases}); ` +
  `speedup geomean ${geo.toFixed(2)}x, >=2x ${summary.at2x}, slower ${summary.slower} (of ${timed.length} timed); ` +
  `compiled ${summary.compiled} of ${summary.claimed}`;

const fmt = (x, d = 1) => (x == null ? '-' : x.toFixed(d));
console.log('');
for (const x of rows) {
  console.log(
    `${(x.speedup != null ? fmt(x.speedup, 2) + 'x' : '-').padStart(8)}  ${x.compiled == null ? ' ' : x.compiled ? 'C' : '.'}  ${x.verdict.padEnd(8)} ${x.name.padEnd(40)} ${x.verdict === 'ok' ? `${fmt(x.originalUs)} -> ${fmt(x.residualUs)} us, ${x.residualLines} lines, ${fmt(x.specMs / 1000)} s` : x.detail}`,
  );
}
console.log('');
console.log(line);

if (jsonOut) fs.writeFileSync(jsonOut, JSON.stringify({ summary, line, rows, env: Object.fromEntries(Object.entries(process.env).filter(([k]) => /^PE_/.test(k))) }, null, 1));
if (mdOut) {
  const out = [];
  out.push('# Interpreters');
  out.push('');
  out.push('> Generated by `node tools/interp.js --md docs/INTERP.md`. Do not edit: run it again.');
  out.push('');
  out.push('Interpreters given fixed programs (`tools/wild/interp/`, see its README), specialized and checked by `tools/wild.js`. `speedup` is the original time over the residual time per pass over the inputs, each in a Node process of its own (above 1 is faster). `compiled` is whether the residual is free of what the case names as interpretation (its `// residue:`).');
  out.push('');
  out.push('```');
  out.push(line);
  out.push('```');
  out.push('');
  out.push('| case | style | verdict | speedup | compiled | original µs | residual µs | residual lines | spec. time |');
  out.push('|---|---|---|--:|:-:|--:|--:|--:|--:|');
  for (const x of rows) {
    out.push(
      `| ${x.name} | ${x.style} | ${x.verdict} | ${x.speedup != null ? fmt(x.speedup, 2) + '×' : '-'} | ${x.compiled == null ? '-' : x.compiled ? 'yes' : 'no'} | ${fmt(x.originalUs, 2)} | ${fmt(x.residualUs, 2)} | ${x.residualLines ?? '-'} | ${x.specMs != null ? fmt(x.specMs / 1000) + ' s' : '-'} |`,
    );
  }
  const bad = rows.filter((x) => x.verdict !== 'ok');
  if (bad.length) {
    out.push('');
    out.push('## Not ok');
    out.push('');
    for (const x of bad) out.push(`- **${x.name}** (${x.verdict}): \`${String(x.detail).replace(/`/g, "'")}\``);
  }
  out.push('');
  fs.writeFileSync(mdOut, out.join('\n'));
}
fs.rmSync(tmp, { recursive: true, force: true });
