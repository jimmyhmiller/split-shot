const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const { createHash } = require('node:crypto');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '../..');
const read = name => fs.readFileSync(path.join(__dirname, name), 'utf8');
const write = (name, text) => fs.writeFileSync(path.join(__dirname, name), text);
const app = read('app.js'), runtime = read('runtime.js'), controller = read('controller.js');
const source = runtime + '\n' + app;
const entries = {
  mount: 'function main(input) { return mount(Operations, input); }',
  update: 'function main(input) { update(Operations, input); }',
  initial: 'function main(input) { return initialState(input); }',
  prepare: 'function main(input) { return prepare(input); }',
  rowMount: 'function main(input) { return mount(JobRow, input); }',
  rowUpdate: 'function main(input) { update(JobRow, input); }'
};
// Cache only specialization, keyed by the complete input and compiler binary.
// All validation and page generation still run on every build.
execFileSync('cargo', ['build', '-q', '--release', '-p', 'js-frontend', '--bin', 'js-frontend'], { cwd: root, stdio: ['ignore','pipe','pipe'] });
const binary = path.join(root, 'target/release/js-frontend');
const compilerHash = createHash('sha256').update(fs.readFileSync(binary)).digest('hex');
const cacheDir = path.join(root, 'target/tiny-update-cache');
fs.mkdirSync(cacheDir, { recursive: true });
const generated = {}, original = {}, compiled = {};
for (const [name, entry] of Object.entries(entries)) {
  const program = source + '\n' + entry;
  const file = name === 'update' ? 'program.js' : name + '-program.js';
  write(file, '// Generated runtime + application + entry point; do not edit.\n' + program);
  const cacheKey = createHash('sha256').update(compilerHash).update(program).digest('hex');
  const cacheFile = path.join(cacheDir, cacheKey + '.js');
  let residual;
  if (fs.existsSync(cacheFile)) residual = fs.readFileSync(cacheFile, 'utf8');
  else {
    const output = execFileSync(binary, ['--js', 'demos/tiny-update/' + file],
      { cwd: root, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024, stdio: ['ignore','pipe','pipe'] });
    residual = output.replace(/^---[^\n]*\n/, '');
    fs.writeFileSync(cacheFile, residual);
  }
  generated[name] = residual;
  original[name] = vm.runInNewContext(program + '\nmain');
  compiled[name] = vm.runInNewContext(residual + '\nmain');
  write('compiled-' + name + '.js', '// Generated by build.cjs; do not edit.\n' + residual);
}
assert(!/\b(render|Operations|JobRow|bindings)\s*\(/.test(generated.update.slice(generated.update.lastIndexOf('function main('))));
assert(generated.mount.includes('createElement') && generated.mount.includes('addEventListener'));
assert(generated.update.includes('nodeValue') && generated.update.includes('setAttribute'));
const isolate = code => '(() => {\n' + code + '\nreturn main;\n})()';
const members = Object.keys(entries).map(name => name + ': ' + isolate(generated[name])).join(',\n');
original.components = { job: { mount: original.rowMount, update: original.rowUpdate } };
compiled.components = { job: { mount: compiled.rowMount, update: compiled.rowUpdate } };
// This standalone bundle includes DOM mounting, events, state ownership, updates,
// and disposal. The shared controller is library code, never page-host logic.
const bundle = '// Generated complete UI bundle; do not edit.\nconst RelayDesk = (() => {\n' +
  controller + '\nconst program = {\n' + members + '\n};\n' +
  'program.components = { job: { mount: program.rowMount, update: program.rowUpdate } };\n' +
  'return { mount: program.mount, update: program.update, initial: program.initial, prepare: program.prepare, components: program.components,\n' +
  'start: function(document, root, observe, options) { return start(program, document, root, observe, options); } };\n})();\n';
write('compiled.js', bundle);
const { verify } = require('./verify.cjs');
const result = verify({ original, compiled, controller, bundle, source, app, isolate });
const benchmark = read('benchmark.js'), host = read('host.js');
// CodeMirror is bundled locally and inlined so the entire demo works offline.
const editorVendor = read('vendor/codemirror.js');
if (/<\/script/i.test(editorVendor)) throw new Error('CodeMirror bundle cannot be embedded inline');
// Recorded results are clearly labeled by environment, and only displayed
// when they match the exact bundle and benchmark source being shown.
const escapeHtml = text => String(text).replace(/[&<>"']/g, char => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'
})[char]);
let recordedRows = '', recordedStatus = 'No recorded timings for this build. Run to measure this browser.';
const resultsPath = path.join(__dirname, 'benchmark-results.json');
if (fs.existsSync(resultsPath)) {
  const report = JSON.parse(read('benchmark-results.json'));
  const inputHash = createHash('sha256').update(bundle).update(benchmark).digest('hex');
  if (report.inputHash === inputHash) {
    recordedStatus = 'Recorded local run: ' + report.environment + ' · ' + report.measuredAt +
      ' · medians of 9 samples. These are jsdom timings; run above for this browser.';
    recordedRows = report.results.map(row => '<tr>' + [row.scenario, row.records.toLocaleString(),
      row.originalUs.toFixed(2) + ' µs', row.compiledUs.toFixed(2) + ' µs',
      row.speedup.toFixed(2) + '×', row.iterationsPerSample.toLocaleString()]
      .map(value => '<td>' + escapeHtml(value) + '</td>').join('') + '</tr>').join('');
  }
}
let phaseSummary = 'No matching phase measurements yet. Run phase-benchmark.cjs to isolate data preparation from DOM patching.', phaseRows = '';
if (fs.existsSync(path.join(__dirname,'phase-benchmark-results.json'))) {
  const report = JSON.parse(read('phase-benchmark-results.json'));
  const hash = createHash('sha256').update(bundle).update(read('phase-benchmark.cjs')).digest('hex');
  if (report.inputHash === hash) {
    const prep = report.results.find(row=>row.records===3840&&row.workload==='operator'&&row.phase==='prepare');
    const patch = report.results.find(row=>row.records===3840&&row.workload==='operator'&&row.phase==='patch');
    phaseSummary = report.environment + '. At 3,840 records, data preparation is ' +
      (100*prep.originalUs/(prep.originalUs+patch.originalUs)).toFixed(0) +
      '% of isolated preparation + patch time. Even a free patch would cap that two-phase speedup at ' +
      ((prep.originalUs+patch.originalUs)/prep.originalUs).toFixed(2) +
      '×. These are Node/jsdom measurements, excluding event/reducer overhead and layout/paint.';
    phaseRows = report.results.map(row=>'<tr>'+[row.records.toLocaleString()+' / '+row.workload,row.phase,
      row.originalUs.toFixed(2)+' µs',row.compiledUs.toFixed(2)+' µs',row.speedup.toFixed(2)+'×']
      .map(value=>'<td>'+escapeHtml(value)+'</td>').join('')+'</tr>').join('');
  }
}
const files = [
  { name: 'app.js', group: 'Application', text: app },
  ...['runtime.js','controller.js'].map(name => ({ name, group: 'UI library', text: read(name) })),
  ...Object.keys(entries).map(name => ({ name: 'compiled-' + name + '.js', group: 'Generated', text: read('compiled-' + name + '.js') })),
  { name: 'compiled.js', group: 'Generated', text: bundle },
  ...['benchmark.js','benchmark.cjs','phase-benchmark.cjs'].map(name => ({ name, group: 'Performance', text: read(name) })),
  ...['host.js','template.html','build.cjs','verify.cjs','verify-dom.cjs','dom-env.cjs','editor/workbench.js','editor/build.cjs','editor/package.json'].map(name => ({ name, group: 'Demo & build', text: read(name) }))
];
for (const name of ['benchmark-results.json','phase-benchmark-results.json']) {
  if (fs.existsSync(path.join(__dirname,name))) files.push({ name, group: 'Recorded measurements', text: read(name) });
}
const replacements = {
  '/* EDITOR_VENDOR */': editorVendor,
  '/* ORIGINAL */': 'const interpretedProgram = {\n' + Object.entries(entries)
    .map(([name, entry]) => name + ': ' + isolate(source + '\n' + entry)).join(',\n') + '\n};\ninterpretedProgram.components = { job: { mount: interpretedProgram.rowMount, update: interpretedProgram.rowUpdate } };\n' + controller,
  '/* COMPILED */': bundle, '/* BENCHMARK */': benchmark, '/* HOST */': host,
  'CODE_FILES': JSON.stringify(files).replace(/</g, '\\u003c'),
  'BENCHMARK_STATUS': escapeHtml(recordedStatus), 'BENCHMARK_ROWS': recordedRows,
  'PHASE_SUMMARY': escapeHtml(phaseSummary), 'PHASE_ROWS': phaseRows
};
let html = read('template.html');
const tokens = Object.keys(replacements).sort((a, b) => b.length - a.length);
const escaped = tokens.map(token => token.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'));
html = html.replace(new RegExp(escaped.join('|'), 'g'), token => replacements[token]);
// Parse the actual embedded browser code, including all generated pieces.
new vm.Script(html.match(/<script>([\s\S]*)<\/script>/)[1]);
write('index.html', html);
console.log(result);
console.log('Generated standalone compiled.js, mount/update/initial residuals, and index.html.');
